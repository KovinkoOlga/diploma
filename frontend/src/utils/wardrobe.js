function ensureArray(value) {
  if (Array.isArray(value)) return value.filter(Boolean);
  if (typeof value === "string" && value.trim()) {
    return value
      .split(",")
      .map((entry) => entry.trim())
      .filter(Boolean);
  }
  return [];
}

function uniqueStrings(values) {
  return Array.from(new Set(ensureArray(values)));
}

export function normalizeStyleName(value) {
  return String(value ?? "")
    .trim()
    .toLowerCase()
    .replace(/\s*[_/\\-]+\s*/g, " ")
    .replace(/\s+/g, " ");
}

function uniqueStyleNames(values) {
  const seen = new Set();
  const names = [];

  for (const value of ensureArray(values)) {
    const name = String(value ?? "").trim();
    const normalized = normalizeStyleName(name);
    if (!name || seen.has(normalized)) continue;
    seen.add(normalized);
    names.push(name);
  }

  return names;
}

function resolveCanonicalStyleName(value, styleOptions = [], selectedStyles = []) {
  const normalized = normalizeStyleName(value);
  if (!normalized) return "";
  return (
    [...selectedStyles, ...styleOptions].find((entry) => normalizeStyleName(entry) === normalized)?.trim() ??
    String(value ?? "").trim()
  );
}

export function finalizeDraftStyleInput(draft, styleOptions = []) {
  const rawInput = String(draft?.styleInput ?? "").trim();
  if (!rawInput) {
    return { ...draft, styleInput: "" };
  }

  const nextStyle = resolveCanonicalStyleName(rawInput, styleOptions, draft?.styles ?? draft?.tags ?? []);
  const nextStyles = uniqueStyleNames([...(draft?.styles ?? draft?.tags ?? []), nextStyle]);
  return {
    ...draft,
    styles: nextStyles,
    tags: nextStyles,
    styleInput: "",
  };
}

function isBlank(value) {
  return String(value ?? "").trim().length === 0;
}

